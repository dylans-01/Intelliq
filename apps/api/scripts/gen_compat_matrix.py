"""Generate the calculation support matrix from the function catalogue and the
executable compatibility cases, so the published matrix cannot drift from
what is actually implemented and tested.

    python scripts/gen_compat_matrix.py > ../../docs/generated/calculation-support-matrix.md
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from intelliq.calc import ast as A  # noqa: E402
from intelliq.calc import functions as F  # noqa: E402
from intelliq.calc.parser import parse  # noqa: E402

spec = importlib.util.spec_from_file_location("compat", ROOT / "tests/integration/test_function_compatibility.py")
compat = importlib.util.module_from_spec(spec)  # type: ignore[arg-type]
spec.loader.exec_module(compat)  # type: ignore[union-attr]

VALIDATION_PENDING = {"RUNNING_SUM", "RUNNING_AVG", "RUNNING_MIN", "RUNNING_MAX", "RUNNING_COUNT", "TOTAL", "RANK_PERCENTILE"}


def cases_for(name: str) -> list[str]:
    out = []
    for formula, expected in compat.ROW_CASES + compat.AGG_CASES + compat.TABLE_CASES:
        if any(isinstance(n, A.Func) and n.name == name for n in parse(formula).walk()):
            out.append(f"`{formula}` → `{expected!r}`")
    return out


def main() -> None:
    print("# Calculation support matrix (generated)\n")
    print("Generated by `apps/api/scripts/gen_compat_matrix.py` from the function catalogue")
    print("(`intelliq/calc/functions.py`) and the executable cases in")
    print("`tests/integration/test_function_compatibility.py`. Every listed function is executed")
    print("against DuckDB in CI; PostgreSQL equivalence is covered by the connector contract suite.\n")
    print("Status: **Tested** = executed with expected values derived from Tableau's documented semantics.")
    print("**Tested · Tableau validation pending** = behaviour chosen where Tableau's documentation is")
    print("ambiguous; must be confirmed against real Tableau output (see docs/07-validation.md).\n")
    by_cat: dict[str, list[F.FunctionDef]] = {}
    for f in F.FUNCTIONS.values():
        by_cat.setdefault(f.category, []).append(f)
    total = 0
    for cat, fns in by_cat.items():
        print(f"## {cat}\n")
        print("| Function | Kind | Status | Description | Semantic notes | Example cases |")
        print("|---|---|---|---|---|---|")
        for f in fns:
            total += 1
            cases = cases_for(f.name)
            status = "Tested · Tableau validation pending" if f.name in VALIDATION_PENDING else ("Tested" if cases else "**Untested**")
            examples = "<br>".join(cases[:2]).replace("|", "\\|")
            print(f"| `{f.name}` | {f.kind} | {status} | {f.description} | {f.notes or '—'} | {examples} |")
        print()
    print(f"_{total} functions catalogued._")


if __name__ == "__main__":
    main()
